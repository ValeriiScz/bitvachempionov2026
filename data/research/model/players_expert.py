"""players_expert.py · v1.3 · 2026-11-09 (план → ОСТАТОК: из сказанного числа турниров вычитаются уже сыгранные обычные турниры
с даты слов; раньше цель «7 турниров до конца года», сказанная 21.09, в ноябре снова целиком накладывалась на остаток календаря
и завышала явку тех, кто уже отыграл свой план) · v1.2 · 2026-09-21 (+Jane 0, Jerry Hurper 6; v1.1 +Lюц 3)
Что игроки сами говорят о планах на остаток года (Валерий, из разговоров).
Ожидаемое число ОБЫЧНЫХ рейтинговых турниров до конца года (финалы серийников — отдельно, они не считаются).
Источник: FACT — слова игрока, переданные Валерием; дата — когда сказано. Ник → uid берётся из леджера."""
import gd_data as g
PLAN={  # ник: (сколько обычных турниров собирался сыграть, с какой даты считать)
 'aptah':(7,'2026-09-21'),       # 21.09: «поедет на 7 турниров»
 'Сью':(7,'2026-09-21'),         # 21.09: «и Сью» (7)
 'Tripok':(6,'2026-09-21'),      # 21.09: «тоже будет гонять»
 'ParadoXx':(6,'2026-09-14'),    # 14.09: «везде катает»
 'DOVOD':(5,'2026-09-14'),       # 14.09: «я 5–6 туриков»
 'RAMZES':(3,'2026-09-14'),      # 14.09: «макс 3»
 'Flame':(2,'2026-09-14'),       # 14.09: «редкий гость»
 'Lюц':(3,'2026-09-21'),         # 21.09: «не прям планирует ездить много, хаотичный»
 'Jane':(0,'2026-09-21'),        # 21.09: не в гонке — не может выезжать (документы)
 'Jerry Hurper':(6,'2026-09-21'),# 21.09: «зарядилась, хочет ещё поиграть»
}
_uid={v['nick']:int(u) for u,v in g.L.items()}
_TI={t['id']:t for y in g.T for t in g.T[y]}
def played_since(u, d0):
    v=g.L.get(str(u)) or {}
    return sum(1 for x in v.get('rp',[]) if x[0]==2026 and (x[2] or '')>d0 and not (_TI.get(x[1]) or {}).get('serial'))
TARGET={}; PLAYED={}
for n,(k,d0) in PLAN.items():
    if n not in _uid: continue
    u=_uid[n]; p=played_since(u,d0); PLAYED[n]=p
    # план выполнен → слов больше нет, решает обычная модель явки (не обнуляем: Lюц «3 турнира» сыграл и всё равно выиграл Варшаву);
    # явный ноль («не выезжает») сохраняем
    if k==0: TARGET[u]=0.0
    elif k-p>0: TARGET[u]=float(k-p)
if __name__=='__main__':
    for n,(k,d0) in PLAN.items(): print(f"{n:13s} план {k} с {d0} · сыграно {PLAYED.get(n,'-')} · остаток {TARGET.get(_uid.get(n),'-')}")
